#!/usr/bin/env python3
"""
Builds sitemap.xml and robots.txt for the whole website.

  python3 tools/make_sitemap.py                      # uses siteUrl from assets/js/config.js
  python3 tools/make_sitemap.py https://www.example.com

Run it again whenever you add pages or change siteUrl.
"""
import datetime
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXCLUDE = {"404.html", "thank-you.html"}
HREFLANG = {"seo-company-uk.html": "en-GB", "seo-company-usa.html": "en-US", "seo-company-india.html": "en-IN"}


def site_url():
    if len(sys.argv) > 1:
        return sys.argv[1].rstrip("/")
    cfg = open(os.path.join(ROOT, "assets", "js", "config.js"), encoding="utf-8").read()
    m = re.search(r'siteUrl:\s*"([^"]+)"', cfg)
    return m.group(1).rstrip("/")


def priority(name):
    if name == "index.html":
        return "1.0"
    if name in ("services.html", "industries.html") or name in HREFLANG:
        return "0.9"
    if name.startswith("seo-for-") and name in HUBS:
        return "0.8"
    if name.endswith("-services.html") or name in ("contact.html",):
        return "0.8"
    if name.startswith("seo-for-"):
        return "0.6"
    if name.startswith("blog"):
        return "0.6"
    if name in ("privacy-policy.html", "terms.html"):
        return "0.3"
    return "0.6"


def blog_date(path, fallback):
    txt = open(path, encoding="utf-8").read()
    m = re.search(r'"dateModified":"(\d{4}-\d{2}-\d{2})"', txt)
    return m.group(1) if m else fallback


base = site_url()
today = datetime.date.today().isoformat()
pages = sorted(f for f in os.listdir(ROOT) if f.endswith(".html") and f not in EXCLUDE)

# hub pages = the 20 category pages listed in main.js
js = open(os.path.join(ROOT, "assets", "js", "main.js"), encoding="utf-8").read()
HUBS = {"seo-for-%s.html" % m for m in re.findall(r'\["([a-z0-9-]+)", "[^"]+"\]', js.split("INDUSTRIES:START")[1].split("INDUSTRIES:END")[0])}

alts = "".join('    <xhtml:link rel="alternate" hreflang="%s" href="%s/%s"/>\n' % (hl, base, f) for f, hl in HREFLANG.items())
out = ['<?xml version="1.0" encoding="UTF-8"?>\n',
       "<!-- Generated by tools/make_sitemap.py from siteUrl in assets/js/config.js -->\n",
       '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n']
for f in pages:
    loc = base + "/" if f == "index.html" else "%s/%s" % (base, f)
    lastmod = blog_date(os.path.join(ROOT, f), today) if f.startswith("blog-") else today
    entry = "  <url><loc>%s</loc><lastmod>%s</lastmod><priority>%s</priority>" % (loc, lastmod, priority(f))
    if f in HREFLANG:
        entry += "\n" + alts + "  "
    out.append(entry + "</url>\n")
out.append("</urlset>\n")
open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8").write("".join(out))

open(os.path.join(ROOT, "robots.txt"), "w", encoding="utf-8").write(
    "User-agent: *\nAllow: /\nDisallow: /thank-you.html\n\nSitemap: %s/sitemap.xml\n" % base)
print("sitemap.xml: %d URLs for %s" % (len(pages), base))
